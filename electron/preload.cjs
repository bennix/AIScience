const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('science', {
  pathForFile: file => webUtils.getPathForFile(file),
  addCodeReference: request => ipcRenderer.invoke('add-code-reference',request),
  onCodeEvidence: callback => {const handler=(_,value)=>callback(value);ipcRenderer.on('code-evidence',handler);return ()=>ipcRenderer.removeListener('code-evidence',handler);},
  attachFiles: remaining => ipcRenderer.invoke('attach-files',remaining),
  pasteAttachment: request => ipcRenderer.invoke('paste-attachment',request),
  removeAttachment: id => ipcRenderer.invoke('remove-attachment',id),
  formalStatus:()=>ipcRenderer.invoke('formal-status'),
  formalSetup:mathlib=>ipcRenderer.invoke('formal-setup',mathlib),
  formalFreeze:request=>ipcRenderer.invoke('formal-freeze',request),
  verifyFormal:projectId=>ipcRenderer.invoke('verify-formal',projectId),
  onFormalProgress:callback=>{const handler=(_,text)=>callback(text);ipcRenderer.on('formal-progress',handler);return()=>ipcRenderer.removeListener('formal-progress',handler);},
  verifyMath: request => ipcRenderer.invoke('verify-math',request),
  onMathStatus: callback => {const handler=(_,check)=>callback(check);ipcRenderer.on('math-status',handler);return ()=>ipcRenderer.removeListener('math-status',handler);},
  load: () => ipcRenderer.invoke('load'),
  save: projects => ipcRenderer.invoke('save', projects),
  checkAPI: () => ipcRenderer.invoke('check-api'),
  indexRAG: projectId => ipcRenderer.invoke('rag-index', projectId),
  importDocument: projectId => ipcRenderer.invoke('import-document', projectId),
  paperFulltext: request => ipcRenderer.invoke('paper-fulltext', request),
  onEvidence: callback => { const handler = (_, value) => callback(value); ipcRenderer.on('rag-evidence', handler); return () => ipcRenderer.removeListener('rag-evidence', handler); },
  settings: settings => ipcRenderer.invoke('settings', settings),
  semanticSearch: request => ipcRenderer.invoke('semantic-search', request),
  search: (query, source) => ipcRenderer.invoke('search', { query, source }),
  generate: request => ipcRenderer.invoke('generate', request),
  cancel: () => ipcRenderer.invoke('cancel'),
  importCSV: options => ipcRenderer.invoke('import-csv', options),
  export: request => ipcRenderer.invoke('export', request),
  saveNotebook: request => ipcRenderer.invoke('save-notebook', request),
  envStatus: () => ipcRenderer.invoke('env-status'),
  envStart: projectId => ipcRenderer.invoke('env-start', projectId),
  envStop: () => ipcRenderer.invoke('env-stop'),
  envOpen: () => ipcRenderer.invoke('env-open'),
  onEnvironment: callback => { const handler = (_, status) => callback(status); ipcRenderer.on('env-status', handler); return () => ipcRenderer.removeListener('env-status', handler); },
  environment: () => ipcRenderer.invoke('environment'),
  openLink: url => ipcRenderer.invoke('open-link', url),
  onChunk: callback => { const handler = (_, event) => callback(event); ipcRenderer.on('ai-chunk', handler); return () => ipcRenderer.removeListener('ai-chunk', handler); }
});
